const { chromium } = require(process.env.PLAYWRIGHT_PACKAGE);
const assert = require('node:assert/strict');
const fs = require('node:fs');

// Use a development-only demo export with bypassAuth=false and no Supabase credentials.
// All edits below apply to the synthetic in-memory demo member.
(async () => {
  const browser = await chromium.launch({ headless: true });
  const origin = process.env.MOBILE_PREVIEW_URL || 'http://127.0.0.1:8813';
  const output = 'tmp/ux-profile-setup';
  fs.mkdirSync(output, { recursive: true });
  const errors = [];
  try {
    for (const [width, locale, textScale] of [[390, 'en', 1], [360, 'is', 1.3]]) {
      const context = await browser.newContext({ viewport: { width, height: 844 }, reducedMotion: 'reduce', geolocation: { latitude: 64.1466, longitude: -21.9426, accuracy: 10 }, permissions: ['geolocation'] });
      const page = await context.newPage();
      page.on('pageerror', error => errors.push(error.message));
      await page.addInitScript(({ locale, textScale }) => {
        localStorage.setItem('rummal.preferences.v1', JSON.stringify({ locale, themeMode: 'dark' }));
        localStorage.setItem('rummal.appearance.v1', JSON.stringify({ darkPreset: 'charcoal', accent: 'amber', textScale, discoveryLayout: 'dense', reducedMotion: true }));
      }, { locale, textScale });
      const en = locale === 'en';
      const button = name => page.getByRole('button', { name, exact: true });
      const next = () => button(en ? 'Continue' : 'Halda áfram').click();
      const shot = async name => {
        await page.evaluate(async () => {
          await document.fonts.ready;
          await Promise.all([...document.images].filter(image => !image.complete).map(image => new Promise(resolve => {
            const timer = setTimeout(resolve, 1500);
            const done = () => { clearTimeout(timer); resolve(); };
            image.addEventListener('load', done, { once: true });
            image.addEventListener('error', done, { once: true });
          })));
        });
        assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false, `${name}: no horizontal overflow at ${width}px`);
        await page.screenshot({ path: `${output}/${name}-${width}-${locale}.png` });
      };
      await page.goto(origin);
      await button(en ? 'Continue with Facebook' : 'Halda áfram með Facebook').waitFor();
      await shot('welcome');
      const instagramInfo = button(en ? 'Add Instagram to your profile' : 'Bæta Instagram við prófílinn');
      await instagramInfo.click();
      await page.getByText(en ? 'Sign in with email, Apple, Google or Facebook, then add your Instagram handle to your profile. You choose what to share.' : 'Skráðu þig inn með netfangi, Apple, Google eða Facebook og bættu svo Instagram-notandanafninu við prófílinn. Þú velur hverju þú deilir.', { exact: true }).waitFor();
      assert.equal(await button(en ? 'Continue with Instagram' : 'Halda áfram með Instagram').count(), 0);
      await shot('welcome-instagram');
      assert.equal(await button(en ? 'Demo mode' : 'Sýnishamur').count(), 1, 'Walkthrough is confined to the local synthetic demo');
      await button(en ? 'Continue with Facebook' : 'Halda áfram með Facebook').click();
      await page.getByRole('heading', { name: en ? 'Choose a language' : 'Veldu tungumál', exact: true }).waitFor();
      await page.getByText(en ? 'Step 1 of 6' : 'Skref 1 af 6', { exact: true }).waitFor();
      await next();
      const dob = () => page.getByRole('button', { name: en ? /^Date of birth/ : /^Fæðingardagur/ });
      const boundary = await page.evaluate(() => { const today = new Date(); const birthday = new Date(Date.UTC(today.getUTCFullYear() - 18, today.getUTCMonth(), today.getUTCDate())); const younger = new Date(birthday); younger.setUTCDate(younger.getUTCDate() + 1); return { adult: birthday.toISOString().slice(0, 10), underage: younger.toISOString().slice(0, 10) }; });
      const dateLabel = iso => new Intl.DateTimeFormat(en ? 'en-GB' : 'is-IS', { weekday: 'long', day: 'numeric', month: 'long', year: 'numeric', timeZone: 'UTC' }).format(new Date(`${iso}T00:00:00Z`));
      const day = iso => page.getByRole('gridcell', { name: dateLabel(iso), exact: true });
      const choosePeriod = async (year, month) => {
        await button(en ? 'Choose birth year' : 'Veldu fæðingarár').click();
        await button(String(year)).click();
        await button(en ? 'Choose month' : 'Veldu mánuð').click();
        await button(new Intl.DateTimeFormat(en ? 'en-GB' : 'is-IS', { month: 'long', timeZone: 'UTC' }).format(new Date(Date.UTC(year, month, 1)))).click();
      };
      await dob().click();
      assert.equal(await page.getByRole('dialog').count(), 1, 'Birthday picker has one modal dialog');
      assert.equal(await button(en ? 'Use date' : 'Nota dagsetningu').getAttribute('aria-disabled'), 'true', 'Suggested adult date is never committed automatically');
      assert.equal(await page.locator('[role="gridcell"][tabindex="0"]').count(), 1, 'Date grid has one Tab stop');
      await page.waitForFunction(label => document.activeElement?.getAttribute('aria-label') === label, dateLabel(boundary.adult), { timeout: 5000 }).catch(async error => {
        console.error('Birthday focus diagnostic', { width, locale, expected: dateLabel(boundary.adult), actual: await page.evaluate(() => document.activeElement?.outerHTML), gridStop: await page.locator('[role="gridcell"][tabindex="0"]').getAttribute('aria-label') });
        await shot('birthday-focus-failure');
        throw error;
      });
      const cellBounds = await day(boundary.adult).boundingBox();
      assert(cellBounds && cellBounds.width >= 44 && cellBounds.height >= 44, 'Calendar dates preserve 44px targets');
      if (await day(boundary.underage).count()) assert.equal(await day(boundary.underage).getAttribute('aria-disabled'), 'true', 'Underage boundary date is disabled');
      assert.equal(await button(en ? 'Next month' : 'Næsti mánuður').getAttribute('aria-disabled'), 'true', 'Calendar cannot browse past the youngest eligible month');
      await shot('birthday-calendar');
      await page.keyboard.press('ArrowLeft');
      const previous = new Date(`${boundary.adult}T00:00:00Z`); previous.setUTCDate(previous.getUTCDate() - 1);
      await page.waitForFunction(label => document.activeElement?.getAttribute('aria-label') === label, dateLabel(previous.toISOString().slice(0, 10)));
      await page.keyboard.press('PageUp');
      await page.keyboard.press('Shift+PageUp');
      assert.equal(await page.locator('[role="gridcell"][tabindex="0"]').count(), 1);
      await page.keyboard.press('Escape');
      await page.getByRole('dialog').waitFor({ state: 'hidden' });
      assert.equal(await dob().evaluate(node => node === document.activeElement), true, 'Escape restores birthday field focus');
      assert.equal(await dob().getAttribute('aria-label'), en ? 'Date of birth' : 'Fæðingardagur', 'Escape discards draft selection');
      await dob().click();
      await button(en ? 'Choose birth year' : 'Veldu fæðingarár').click();
      await shot('birthday-years');
      await button('2004').click();
      await button(en ? 'Choose month' : 'Veldu mánuð').click();
      await shot('birthday-months');
      await button(en ? 'February' : 'febrúar').click();
      await day('2004-02-29').click();
      await page.getByRole('button', { name: en ? 'Cancel' : 'Hætta við', exact: true }).last().click();
      await page.getByRole('dialog').waitFor({ state: 'hidden' });
      assert.equal(await dob().getAttribute('aria-label'), en ? 'Date of birth' : 'Fæðingardagur', 'Cancel preserves the committed birthday');
      await dob().click();
      const adult = new Date(`${boundary.adult}T00:00:00Z`);
      await choosePeriod(adult.getUTCFullYear(), adult.getUTCMonth());
      await day(boundary.adult).click();
      assert.equal(await day(boundary.adult).getAttribute('aria-selected'), 'true');
      await button(en ? 'Use date' : 'Nota dagsetningu').click();
      await page.getByRole('dialog').waitFor({ state: 'hidden' });
      assert.equal(await dob().getAttribute('aria-label'), `${en ? 'Date of birth' : 'Fæðingardagur'}: ${dateLabel(boundary.adult)}`, 'Calendar commits a UTC date in the existing field');
      await next();
      const consent = page.getByRole('checkbox');
      assert.equal(await consent.count(), 4, 'All four explicit consents remain present');
      for (let i = 0; i < 3; i++) await consent.nth(i).click();
      assert.equal(await consent.nth(3).getAttribute('aria-checked'), 'false', 'Sensitive consent is not implicit');
      await next();
      await page.getByText(en ? 'Accept every item to continue.' : 'Samþykkja þarf öll atriðin til að halda áfram.', { exact: true }).waitFor();
      await shot('consent');
      await consent.nth(3).click();
      await next();
      await page.getByRole('heading', { name: en ? 'Start with you' : 'Byrjum á þér', exact: true }).waitFor();
      const name = page.getByRole('textbox', { name: en ? 'Display name' : 'Birtingarnafn', exact: true });
      await name.fill('Alex QA');
      await page.getByText(en ? 'Sexual orientation' : 'Kynhneigð', { exact: true }).waitFor();
      await page.getByRole('checkbox', { name: en ? 'Gay' : 'Hommi', exact: true }).click();
      const privacyChoice = page.getByRole('checkbox', { name: en ? 'Rather not say' : 'Vil ekki gefa upp', exact: true });
      const notApplicable = page.getByRole('checkbox', { name: en ? 'Not applicable' : 'Á ekki við', exact: true });
      await privacyChoice.click();
      assert.equal(await page.getByRole('checkbox', { name: en ? 'Gay' : 'Hommi', exact: true }).getAttribute('aria-checked'), 'false');
      assert.equal(await privacyChoice.getAttribute('aria-checked'), 'true');
      await notApplicable.click();
      assert.equal(await notApplicable.getAttribute('aria-checked'), 'true');
      assert.equal(await privacyChoice.getAttribute('aria-checked'), 'false', 'Privacy choices are mutually exclusive');
      await shot('basics');
      await next();
      await page.getByRole('heading', { name: en ? 'What brings you here?' : 'Hvað viltu finna?', exact: true }).waitFor();
      assert.equal(await page.getByRole('textbox', { name: 'Instagram', exact: true }).count(), 0, 'Optional extras start collapsed');
      await next();
      await page.getByText(en ? 'Choose at least one thing you are looking for.' : 'Veldu að minnsta kosti eitt sem þú ert að leita að.', { exact: true }).waitFor();
      const chat = page.getByRole('checkbox', { name: en ? 'Chat' : 'Spjall', exact: true });
      await chat.click();
      assert.equal(await chat.getAttribute('aria-checked'), 'true');
      assert.equal(await page.getByText(en ? 'Choose at least one thing you are looking for.' : 'Veldu að minnsta kosti eitt sem þú ert að leita að.', { exact: true }).count(), 0, 'Resolving the selection clears its old validation message');
      await shot('intentions');
      await button(en ? 'Add a little more' : 'Bættu við meiru').click();
      await page.getByRole('textbox', { name: 'Instagram', exact: true }).fill('alex_setup_demo');
      await next();
      const locate = button(en ? 'Allow location' : 'Leyfa staðsetningu');
      await locate.waitFor();
      await shot('location');
      await locate.click();
      await page.getByRole('tab', { name: /Profile|Prófíll/ }).waitFor();
      await page.getByRole('tab', { name: /Profile|Prófíll/ }).click();
      await page.getByRole('textbox', { name: en ? 'Display name' : 'Birtingarnafn', exact: true }).waitFor();
      await shot('profile-edit');
      const save = button(en ? 'Save' : 'Vista');
      const bounds = await save.boundingBox();
      assert(bounds && bounds.y >= 0 && bounds.y + bounds.height <= 844, 'Save stays visible in the fixed action footer');
      await button(en ? 'Sexual orientation' : 'Kynhneigð').click();
      assert.equal(await notApplicable.getAttribute('aria-checked'), 'true', 'A standalone privacy orientation survives onboarding');
      await page.getByRole('checkbox', { name: en ? 'Gay' : 'Hommi', exact: true }).click();
      assert.equal(await notApplicable.getAttribute('aria-checked'), 'false');
      await privacyChoice.click();
      assert.equal(await page.getByRole('checkbox', { name: en ? 'Gay' : 'Hommi', exact: true }).getAttribute('aria-checked'), 'false');
      await save.click();
      await page.getByText(en ? 'Profile saved.' : 'Prófíll vistaður.', { exact: true }).waitFor();
      await button(en ? 'Sexual orientation' : 'Kynhneigð').click();
      await button(en ? 'Sexual orientation' : 'Kynhneigð').click();
      assert.equal(await privacyChoice.getAttribute('aria-checked'), 'true', 'Saved orientation privacy choice persists when reopened');
      await button(en ? 'Sexual orientation' : 'Kynhneigð').click();
      await button(en ? 'Social links' : 'Samfélagsmiðlar').click();
      const instagram = page.getByRole('textbox', { name: 'Instagram', exact: true });
      assert.equal(await instagram.inputValue(), 'alex_setup_demo', 'Onboarding preserves optional Instagram handle');
      await instagram.fill('alex_profile_demo');
      await save.click();
      await page.getByText(en ? 'Profile saved.' : 'Prófíll vistaður.', { exact: true }).waitFor();
      await button(en ? 'Preview' : 'Forskoða').click();
      await page.getByRole('heading', { name: en ? 'Your profile' : 'Prófíllinn þinn', exact: true }).waitFor();
      await page.getByText('instagram: alex_profile_demo', { exact: true }).waitFor();
      await shot('profile-preview');
      await button(en ? 'Close' : 'Loka').click();
      await button(en ? 'Looking for' : 'Leita að').click();
      await page.getByRole('checkbox', { name: en ? 'Chat' : 'Spjall', exact: true }).waitFor();
      await shot('profile-intentions');
      await context.close();
    }
    // Check dismissal after an actual fade, as well as Space activation and the modal Tab trap.
    const animated = await browser.newContext({ viewport: { width: 390, height: 844 }, reducedMotion: 'no-preference' });
    const fade = await animated.newPage();
    fade.on('pageerror', error => errors.push(error.message));
    await fade.addInitScript(() => {
      localStorage.setItem('rummal.preferences.v1', JSON.stringify({ locale: 'en', themeMode: 'dark' }));
      localStorage.setItem('rummal.appearance.v1', JSON.stringify({ darkPreset: 'charcoal', accent: 'amber', textScale: 1, reducedMotion: false }));
    });
    await fade.goto(origin);
    await fade.getByRole('button', { name: 'Continue with Facebook', exact: true }).click();
    await fade.getByRole('button', { name: 'Continue', exact: true }).click();
    const field = () => fade.getByRole('button', { name: /^Date of birth/ });
    await field().click();
    const dialog = fade.getByRole('dialog', { name: 'Date of birth', exact: true });
    await dialog.waitFor();
    await fade.waitForFunction(() => document.activeElement?.getAttribute('role') === 'gridcell');
    assert.equal(await dialog.count(), 1);
    await fade.keyboard.press('Space');
    assert.equal(await fade.locator('[role="gridcell"][tabindex="0"]').getAttribute('aria-selected'), 'true', 'Space selects a date in the grid');
    for (let index = 0; index < 15; index++) {
      await fade.keyboard.press('Tab');
      assert.equal(await dialog.evaluate(node => node.contains(document.activeElement)), true, 'Tab focus stays inside the date dialog');
    }
    await fade.getByRole('button', { name: 'Cancel', exact: true }).click();
    await dialog.waitFor({ state: 'hidden' });
    await fade.waitForFunction(() => document.activeElement?.getAttribute('aria-label') === 'Date of birth');
    assert.equal(await field().getAttribute('aria-label'), 'Date of birth', 'Fade cancellation preserves birthday and restores field focus');
    await field().click();
    await dialog.waitFor();
    await fade.waitForFunction(() => document.activeElement?.getAttribute('role') === 'gridcell');
    await fade.keyboard.press('Enter');
    await fade.getByRole('button', { name: 'Use date', exact: true }).click();
    await dialog.waitFor({ state: 'hidden' });
    const committed = await field().getAttribute('aria-label');
    await field().click();
    await dialog.waitFor();
    await fade.waitForFunction(() => document.activeElement?.getAttribute('role') === 'gridcell');
    await fade.keyboard.press('ArrowLeft');
    await fade.keyboard.press('Space');
    await fade.keyboard.press('Escape');
    await dialog.waitFor({ state: 'hidden' });
    await fade.waitForFunction(label => document.activeElement?.getAttribute('aria-label') === label, committed);
    assert.equal(await field().getAttribute('aria-label'), committed, 'Escape discards changed draft and restores focus after a fade');
    await animated.close();
    assert.equal(errors.length, 0, errors.join('\n'));
    console.log('PASS: welcome providers/Instagram explainer, six-stage onboarding, accessible birthday calendar/adult boundary, orientation privacy choices, four explicit consents, Reykjavik geolocation, profile Instagram save and draft preview; 390px English and 360px Icelandic at 1.3 text size. No runtime errors.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
