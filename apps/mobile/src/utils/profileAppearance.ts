export type ProfileAppearance = {
  palette: 'default' | 'fern' | 'violet' | 'ember' | 'ocean';
  banner: 'photo' | 'aurora' | 'sunset' | 'midnight';
  effect: 'none' | 'fireflies' | 'sparkles' | 'hearts';
  avatarBorder: 'none' | 'glow' | 'rainbow' | 'ferns' | 'orbit';
};

export const defaultProfileAppearance: Readonly<ProfileAppearance> = {
  palette: 'default', banner: 'photo', effect: 'none', avatarBorder: 'none',
};

const choices = {
  palette: ['default', 'fern', 'violet', 'ember', 'ocean'],
  banner: ['photo', 'aurora', 'sunset', 'midnight'],
  effect: ['none', 'fireflies', 'sparkles', 'hearts'],
  avatarBorder: ['none', 'glow', 'rainbow', 'ferns', 'orbit'],
} as const;

/** Forgiving reads keep profiles from older clients and malformed legacy data usable. */
export function normalizeProfileAppearance(value: unknown): ProfileAppearance {
  const input = value && typeof value === 'object' && !Array.isArray(value) ? value as Record<string, unknown> : {};
  const result: ProfileAppearance = { ...defaultProfileAppearance };
  for (const key of Object.keys(choices) as Array<keyof ProfileAppearance>) {
    const selected = input[key];
    if (typeof selected === 'string' && (choices[key] as readonly string[]).includes(selected)) {
      Object.assign(result, { [key]: selected });
    }
  }
  return result;
}

/** Writes reject unsupported fields and selections instead of silently changing a choice. */
export function validateProfileAppearance(value: unknown): ProfileAppearance {
  if (!value || typeof value !== 'object' || Array.isArray(value)) throw new Error('invalid_profile_appearance');
  const input = value as Record<string, unknown>;
  const keys = Object.keys(choices) as Array<keyof ProfileAppearance>;
  if (Object.keys(input).length !== keys.length || keys.some(key =>
    !Object.hasOwn(input, key) || typeof input[key] !== 'string' || !(choices[key] as readonly string[]).includes(input[key] as string)
  )) throw new Error('invalid_profile_appearance');
  return normalizeProfileAppearance(input);
}

