/** GIF thumbnails are generated by the media worker from the sanitized first frame. */
export function profilePhotoPosterPath(path: string): string | undefined {
  return /\.gif$/i.test(path) ? path.replace(/\.gif$/i, '-thumb.jpg') : undefined;
}
