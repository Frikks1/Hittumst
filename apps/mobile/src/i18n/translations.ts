export const translations = { is, en } as const;

export function translate(locale: Locale, key: TranslationKey, variables?: Record<string, string | number>): string {
  const template = translations[locale][key] ?? translations.is[key];
  if (!variables) return template;
  return Object.entries(variables).reduce(
    (value, [name, replacement]) => value.replaceAll(`{{${name}}}`, String(replacement)),
    template
  );
}
